from pathlib import Path
from typing import Any, Protocol


class Game(Protocol):
    game_id: str

    @property
    def current_player(self) -> str: ...

    def observation(self) -> dict[str, Any]: ...
    def action_schema(self) -> dict[str, Any]: ...
    def prompt(self) -> str: ...
    def step(self, action: dict[str, Any]) -> None: ...
    def snapshot(self) -> dict[str, Any]: ...
    def outcome(self) -> dict[str, Any] | None: ...


class Harness(Protocol):
    metadata: dict[str, Any]

    async def start(self) -> None: ...
    async def act(self, prompt: str, schema: dict, ply: int, images: list[Path] | None = None) -> str: ...
    async def close(self) -> None: ...


class Renderer(Protocol):
    def render(self, snapshot: dict, metadata: dict, destination: Path) -> None: ...


class ObservationRenderer(Protocol):
    """Render the current state for the player, independently of the broadcast UI."""

    def __call__(self, snapshot: dict, destination: Path) -> None: ...
